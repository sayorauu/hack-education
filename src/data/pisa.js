/** Подсчёт результата по заранее заданной шкале. */
export function scorePisa(answers) {
  const res = {};
  for (const domain of ['math', 'reading']) {
    const items = PISA_ITEMS.filter((q) => q.domain === domain);
    const total = items.reduce((s, q) => s + q.w, 0);
    const got = items.reduce((s, q) => s + (answers[q.id] === q.answer ? q.w : 0), 0);
    const correct = items.filter((q) => answers[q.id] === q.answer).length;
    const score = Math.round(300 + 350 * (got / total));
    res[domain] = { score, correct, of: items.length, level: levelOf(domain, score) };
  }
  res.total = Math.round((res.math.score + res.reading.score) / 2);
  return res;
}
